function extractDefaultSettings(source, i18nSource) {
  const marker = 'export const DEFAULT_SETTINGS ='
  const start = source.indexOf(marker)
  if (start === -1) {
    throw new Error('DEFAULT_SETTINGS export was not found')
  }
  const arrayStart = source.indexOf('[', start)
  const endMarker = '] as const satisfies SettingConfig[]'
  const arrayEnd = source.indexOf(endMarker, arrayStart)
  if (arrayStart === -1 || arrayEnd === -1) {
    throw new Error('DEFAULT_SETTINGS array bounds were not found')
  }
  const localeLanguages = [
    ...i18nSource.matchAll(/language:\s*'([^']+)'/g),
  ].map((match) => match[1])
  if (localeLanguages.length === 0) {
    throw new Error('i18n locale languages were not found')
  }
  const expression = source
    .slice(arrayStart, arrayEnd + 1)
    .replaceAll(
      /i18nOptions\.locales\.map\(\(\{\s*language\s*\}\)\s*=>\s*language\)/g,
      JSON.stringify(localeLanguages),
    )
  return Function(`"use strict"; return (${expression});`)()
}

function encodeSettingValue(type, value) {
  if (value === null || value === undefined) {
    return null
  }
  switch (type) {
    case 'string':
      if (typeof value !== 'string') {
        throw new Error(`Expected string default, got ${typeof value}`)
      }
      return value
    case 'number': {
      if (typeof value !== 'number' || !Number.isFinite(value)) {
        throw new Error(`Expected finite number default, got ${value}`)
      }
      const stored = JSON.stringify(Object.is(value, -0) ? 0 : value)
      if (!/^-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?$/.test(stored)) {
        throw new Error(`Invalid JSON number default ${stored}`)
      }
      return stored
    }
    case 'boolean':
      if (typeof value !== 'boolean') {
        throw new Error(`Expected boolean default, got ${typeof value}`)
      }
      return value ? 'true' : 'false'
    case 'json': {
      if (typeof value !== 'object' || value === null || Array.isArray(value)) {
        throw new Error('Expected object JSON default')
      }
      return JSON.stringify(value)
    }
    default:
      throw new Error(`Unsupported setting type ${JSON.stringify(type)}`)
  }
}

function goStringPointer(value) {
  if (value === null || value === undefined) {
    return 'nil'
  }
  return `stringPtr(${JSON.stringify(String(value))})`
}

function goField(name, value) {
  return `\t\t${`${name}:`.padEnd(14)}${value},`
}

const defaultSettings = extractDefaultSettings(
  settingsSource,
  i18nOptionsSource,
)
const defaultSettingsMetadata = defaultSettings.map((setting) => {
  const storedDefault = encodeSettingValue(setting.type, setting.defaultValue)
  return {
    namespace: setting.namespace,
    key: setting.key,
    type: setting.type,
    value: storedDefault,
    defaultValue: storedDefault,
    label: setting.label ?? null,
    description: setting.description ?? null,
    isPublic: setting.isPublic ?? false,
    isReadonly: setting.isReadonly ?? false,
    isSecret: setting.isSecret ?? false,
    enum: setting.enum ? [...setting.enum] : null,
  }
})

