const [journal, requirements, settingsSource, i18nOptionsSource] =
  await Promise.all([
    readJSON(journalPath),
    readJSON(requirementsPath),
    readFile(settingsSourcePath, 'utf8'),
    readFile(i18nOptionsPath, 'utf8'),
  ])
const entries = await Promise.all(
  journal.entries.map(async ({ tag, when }) => {
    const sql = await readFile(join(migrations, `${tag}.sql`), 'utf8')
    return {
      tag,
      createdAt: when,
      hash: createHash('sha256').update(sql).digest('hex'),
      sql,
    }
  }),
)
const migrationSQL = entries.map(({ sql }) => sql)
const migrationMetadata = entries.map(({ tag, createdAt, hash }) => ({
  tag,
  createdAt,
  hash,
}))

function canonicalSchemaSQL(value) {
  return value.toLowerCase().replaceAll(/[`";\s]/g, '')
}

const requiredTriggers = Object.fromEntries(
  requirements.requiredTriggers.map((name) => {
    const definition = migrationSQL
      .flatMap((source) => source.split('--> statement-breakpoint'))
      .find((statement) => {
        const match = statement.match(
          /create\s+trigger\s+[`"]?([^`"\s]+)[`"]?/i,
        )
        return match?.[1] === name
      })
    if (!definition) {
      throw new Error(`Required trigger ${name} was not found in migrations`)
    }
    return [
      name,
      createHash('sha256').update(canonicalSchemaSQL(definition)).digest('hex'),
    ]
  }),
)
const requiredTableEntries = Object.entries(requirements.requiredTables).sort(
  ([left], [right]) => left.localeCompare(right),
)
const requiredTableKeyWidth = Math.max(
  ...requiredTableEntries.map(([table]) => `${JSON.stringify(table)}:`.length),
)

