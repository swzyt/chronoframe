function nestedJSON(value) {
  return JSON.stringify(value, null, 2).replaceAll('\n', '\n  ')
}

const contract = `{
  "version": 2,
  "authority": "backend/nodejs/database/migrations/meta/_journal.json + SQL bytes + backend/contracts/schema-requirements.json",
  "journalVersion": ${JSON.stringify(journal.version)},
  "requirementsVersion": ${JSON.stringify(requirements.version)},
  "requiredTables": {
${Object.entries(requirements.requiredTables)
  .map(([table, columns], index, all) => {
    const suffix = index === all.length - 1 ? '' : ','
    const prefix = `    ${JSON.stringify(table)}: `
    const inline = `[${columns.map((column) => JSON.stringify(column)).join(', ')}]`
    if (`${prefix}${inline}${suffix}`.length <= 80) {
      return `${prefix}${inline}${suffix}`
    }
    return `${prefix}[\n${columns.map((column) => `      ${JSON.stringify(column)}`).join(',\n')}\n    ]${suffix}`
  })
  .join('\n')}
  },
  "requiredIndexes": ${nestedJSON(requirements.requiredIndexes)},
  "requiredTriggers": ${nestedJSON(requiredTriggers)},
  "migrations": ${nestedJSON(migrationMetadata)}
}
`

const settingsContract = `{
  "version": 1,
  "authority": "backend/nodejs/services/settings/contants.ts + i18n/i18n.options.ts",
  "settings": ${nestedJSON(defaultSettingsMetadata)}
}
`

if (process.argv.includes('--check')) {
  const [current, currentContract, currentSettings, currentSettingsContract] =
    await Promise.all([
      readFile(outputPath, 'utf8').catch(() => ''),
      readFile(contractPath, 'utf8').catch(() => ''),
      readFile(settingsOutputPath, 'utf8').catch(() => ''),
      readFile(settingsContractPath, 'utf8').catch(() => ''),
    ])
  if (
    current !== source ||
    currentContract !== contract ||
    currentSettings !== settingsSourceGo ||
    currentSettingsContract !== settingsContract
  ) {
    console.error(
      'Go generated contracts are stale; run: node scripts/generate-go-migrations.mjs',
    )
    process.exit(1)
  }
} else {
  await Promise.all([
    writeFile(outputPath, source),
    writeFile(contractPath, contract),
    writeFile(settingsOutputPath, settingsSourceGo),
    writeFile(settingsContractPath, settingsContract),
  ])
}

async function readJSON(path) {
  return JSON.parse(await readFile(path, 'utf8'))
}
